CREATE TABLE IF NOT EXISTS public.rental_listings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint,
    category varchar(12) NOT NULL DEFAULT 'home',
    transaction_type varchar(8) NOT NULL DEFAULT 'rent',
    title varchar(180) NOT NULL,
    slug varchar(200) NOT NULL UNIQUE,
    description text NOT NULL,
    address varchar(240) NOT NULL DEFAULT '',
    city varchar(100) NOT NULL,
    state varchar(100) NOT NULL,
    property_type varchar(60) NOT NULL DEFAULT '',
    bedrooms smallint NOT NULL DEFAULT 1,
    bathrooms smallint NOT NULL DEFAULT 1,
    annual_rent bigint,
    sale_price bigint,
    status varchar(20) NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.rental_listings
    ADD COLUMN IF NOT EXISTS owner_auth_id uuid
    REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS public.rental_listing_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.rental_listings(id) ON DELETE CASCADE,
    image varchar(1000) NOT NULL,
    caption varchar(160) NOT NULL DEFAULT '',
    position smallint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.rental_listing_photos
    ALTER COLUMN image TYPE varchar(1000);

CREATE TABLE IF NOT EXISTS public.rental_inspection_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.rental_listings(id) ON DELETE RESTRICT,
    guest_name varchar(160) NOT NULL,
    email varchar(254) NOT NULL,
    phone varchar(40) NOT NULL,
    preferred_date date,
    message text NOT NULL DEFAULT '',
    status varchar(12) NOT NULL DEFAULT 'new',
    staff_notes text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rental_property_listing_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name varchar(160) NOT NULL,
    phone varchar(40) NOT NULL,
    property_type varchar(20) NOT NULL,
    address varchar(500) NOT NULL,
    terms_accepted boolean NOT NULL DEFAULT false,
    terms_accepted_at timestamptz NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'new',
    staff_notes text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rental_api_owner_profiles (
    user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username varchar(150) NOT NULL UNIQUE,
    first_name varchar(150) NOT NULL DEFAULT '',
    last_name varchar(150) NOT NULL DEFAULT '',
    email varchar(254) NOT NULL UNIQUE,
    owner_type varchar(8) NOT NULL DEFAULT 'land',
    phone varchar(40) NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.create_rental_owner_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NEW.raw_user_meta_data ->> 'app_role' = 'rental_owner' THEN
        INSERT INTO public.rental_api_owner_profiles (
            user_id,
            username,
            first_name,
            last_name,
            email,
            owner_type,
            phone,
            status
        )
        VALUES (
            NEW.id,
            NEW.raw_user_meta_data ->> 'username',
            COALESCE(NEW.raw_user_meta_data ->> 'first_name', ''),
            COALESCE(NEW.raw_user_meta_data ->> 'last_name', ''),
            lower(NEW.email),
            'land',
            NEW.raw_user_meta_data ->> 'phone',
            'pending'
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_rental_owner_auth_user_created ON auth.users;
CREATE TRIGGER on_rental_owner_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.create_rental_owner_profile();

REVOKE ALL ON FUNCTION public.create_rental_owner_profile() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_rental_owner_profile()
    TO supabase_auth_admin, service_role;

CREATE OR REPLACE FUNCTION public.set_rental_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.set_rental_updated_at() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_rental_updated_at() TO service_role;

DROP TRIGGER IF EXISTS rental_listings_set_updated_at ON public.rental_listings;
CREATE TRIGGER rental_listings_set_updated_at
    BEFORE UPDATE ON public.rental_listings
    FOR EACH ROW
