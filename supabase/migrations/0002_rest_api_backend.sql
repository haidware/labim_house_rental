DROP POLICY IF EXISTS "Public can read published rental listings"
    ON public.rental_listings;
CREATE POLICY "Public can read published rental listings"
    ON public.rental_listings
    FOR SELECT
    TO anon, authenticated
    USING (status = 'published');

DROP POLICY IF EXISTS "Public can read photos for published rental listings"
    ON public.rental_listing_photos;
CREATE POLICY "Public can read photos for published rental listings"
    ON public.rental_listing_photos
    FOR SELECT
    TO anon, authenticated
    USING (
        EXISTS (
            SELECT 1
            FROM public.rental_listings
            WHERE rental_listings.id = rental_listing_photos.listing_id
              AND rental_listings.status = 'published'
        )
    );

INSERT INTO storage.buckets (id, name, public)
VALUES ('rental-listing-photos', 'rental-listing-photos', true)
ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public;

DROP POLICY IF EXISTS "Public can view rental listing photos"
    ON storage.objects;
CREATE POLICY "Public can view rental listing photos"
    ON storage.objects
    FOR SELECT
    TO anon, authenticated
    USING (bucket_id = 'rental-listing-photos');
